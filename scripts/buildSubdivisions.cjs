// Generate 8 subdivisions per district
const allSubdivisions = [];
const allDistricts = [];

DISTRICT_DATA.forEach((d) => {
  const subdivisions = [];
  for (let i = 0; i < 8; i++) {
    const angle = (i / 8) * 2 * Math.PI - Math.PI / 2;
    const dist = 14 + (i % 3) * 3;
    const sx = Math.round(d.x + Math.cos(angle) * dist);
    const sy = Math.round(d.y + Math.sin(angle) * dist);

    const sub = {
      id: d.id + '_s' + (i + 1),
      districtId: d.id,
      districtName: d.name,
      division: d.div,
      sectorName: d.names[i],
      sectorIndex: i,
      elevationMeters: d.elevs[i],
      population: d.pops[i],
      x: sx,
      y: sy,
      r: 16 + (i % 2) * 2
    };
    subdivisions.push(sub);
    allSubdivisions.push(sub);
  }

  allDistricts.push({
    id: d.id,
    name: d.name,
    bnName: d.bnName,
    division: d.div,
    population: d.pop,
    areaKm2: d.area,
    centerCoordinates: { x: d.x, y: d.y },
    subdivisions
  });
});

